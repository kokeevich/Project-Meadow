using System;
using ProjectMeadow.Animals;
class Program
{
    static void Check(bool ok, string name) { if (!ok) throw new Exception(name); Console.WriteLine("PASS: " + name); }
    static void Main()
    {
        var inventory = new ProjectMeadow.Inventory.InventoryService(2);
        int changes = 0;
        inventory.Changed += () => changes++;
        Check(!inventory.TryAdd(null) && !inventory.TryAdd("egg", 0), "Reject invalid inventory additions");
        Check(inventory.TryAdd("egg", 2) && !inventory.TryAdd("egg"), "Capacity enforced");
        Check(inventory.Used == 2 && inventory.Count("egg") == 2 && changes == 1, "Failed addition preserves inventory");
        Check(!inventory.TryRemove("egg", 3) && !inventory.TryRemove("egg", -1), "Invalid removal is atomic");
        Check(inventory.TryRemove("egg") && inventory.TryAdd("milk"), "Removal frees capacity");
        Check(inventory.Count("egg") == 1 && inventory.Count("milk") == 1 && inventory.Used == 2, "Mixed inventory counts");
        Check(!inventory.TryAdd("egg", int.MaxValue), "Large additions cannot overflow capacity");
        var stock = new ProjectMeadow.Inventory.InventoryService(10);
        var economy = new ProjectMeadow.Economy.EconomyService(stock);
        Check(!economy.TryDispatch("egg", 1) && !economy.TryBuyChicken(() => true), "Empty farm cannot sell or purchase");
        stock.TryAdd("egg", 5);
        Check(!economy.TryDispatch("milk", 1) && !economy.TryDispatch("egg", 0) && !economy.TryDispatch("egg", 6), "Invalid cargo rejected");
        Check(economy.TryDispatch("egg", 5) && stock.Used == 0 && economy.Currency.Balance == 0, "Dispatch removes cargo without early payment");
        Check(!economy.TryDispatch("egg", 1), "Truck cannot dispatch twice");
        economy.Tick(float.NaN); economy.Tick(-1); economy.Tick(4);
        Check(economy.Busy && economy.Currency.Balance == 0, "Invalid time ignored and trip takes full duration");
        economy.Tick(1);
        Check(!economy.Busy && economy.Currency.Balance == 25 && economy.EggsSold == 5, "Truck returns with exact payment");
        economy.Tick(100);
        Check(economy.Currency.Balance == 25, "No duplicate payment");
        Check(!economy.TryBuyChicken(() => false) && economy.Currency.Balance == 25, "Failed spawn refunds coins");
        try { economy.TryBuyChicken(() => throw new Exception("spawn failed")); } catch (Exception) {}
        Check(economy.Currency.Balance == 25, "Spawn exception refunds coins");
        int spawned = 0;
        Check(economy.TryBuyChicken(() => { spawned++; return true; }) && economy.Currency.Balance == 0, "Successful purchase deducts price");
        Check(!economy.TryBuyChicken(() => { spawned++; return true; }) && spawned == 1, "Insufficient funds never spawn chicken");
        var wallet = new ProjectMeadow.Economy.CurrencyService();
        Check(!wallet.TryCredit(-1) && wallet.TryCredit(int.MaxValue) && !wallet.TryCredit(1), "Currency rejects negatives and overflow");
        var levelStock = new ProjectMeadow.Inventory.InventoryService(10);
        var levelEconomy = new ProjectMeadow.Economy.EconomyService(levelStock);
        var objective = new ProjectMeadow.Objectives.SellObjective(10);
        Check(!objective.Observe(-5) && objective.Progress == 0, "Negative progress ignored");
        levelStock.TryAdd("egg", 10);
        Check(!objective.Observe(levelEconomy.EggsSold), "Collecting eggs does not complete objective");
        levelEconomy.TryDispatch("egg", 5);
        Check(!objective.Observe(levelEconomy.EggsSold), "Cargo in transit does not count");
        levelEconomy.Tick(5);
        Check(!objective.Observe(levelEconomy.EggsSold) && objective.Progress == 5, "Partial delivered sale updates objective");
        objective.Observe(0);
        Check(objective.Progress == 5, "Objective progress cannot regress");
        levelEconomy.TryDispatch("egg", 5); levelEconomy.Tick(5);
        Check(objective.Observe(levelEconomy.EggsSold) && objective.Complete, "Ten delivered eggs complete level");
        Check(!objective.Observe(10) && !objective.Observe(100) && objective.Progress == 10, "Completion fires once and clamps progress");
        Check(!new ProjectMeadow.Objectives.SellObjective(10).Complete, "New level starts incomplete");
        bool rejectedTarget = false;
        try { new ProjectMeadow.Objectives.SellObjective(0); } catch (ArgumentOutOfRangeException) { rejectedTarget = true; }
        Check(rejectedTarget, "Invalid level target rejected");
        var millStock = new ProjectMeadow.Inventory.InventoryService(10);
        var millEconomy = new ProjectMeadow.Economy.EconomyService(millStock);
        var mill = new ProjectMeadow.Production.ProductionService(millStock, millEconomy.Currency, "grain", 2, "flour", 1, 6);
        Check(!mill.TryQueue(), "Mill rejects missing ingredients");
        millStock.TryAdd("grain", 8);
        Check(mill.TryQueue() && mill.TryQueue() && mill.TryQueue() && !mill.TryQueue(), "Mill queue limited to three jobs");
        Check(millStock.Count("grain") == 2, "Queued recipes reserve ingredients exactly once");
        mill.Tick(5);
        Check(millStock.Count("flour") == 0 && mill.Queued == 3, "Recipe cannot finish early");
        mill.Tick(13);
        Check(millStock.Count("flour") == 3 && mill.Queued == 0, "Large frame completes queued production correctly");
        millStock.TryRemove("flour", 3);
        Check(mill.TryQueue(), "Queue can restart");
        millStock.TryAdd("egg", 10); mill.Tick(6);
        Check(mill.OutputBlocked && mill.Queued == 1 && millStock.Count("flour") == 0, "Full storage holds completed product");
        millStock.TryRemove("egg"); mill.Tick(0);
        Check(millStock.Count("flour") == 1 && mill.Queued == 0, "Product delivered once space becomes available");
        Check(!mill.TryUpgrade(), "Upgrade requires money");
        millEconomy.Currency.TryCredit(60);
        Check(mill.TryUpgrade() && mill.TryUpgrade() && !mill.TryUpgrade() && millEconomy.Currency.Balance == 0 && mill.NextDuration == 4, "Two paid upgrades reduce future production time");
        millStock.TryRemove("egg", 9);
        Check(millEconomy.TryDispatch("flour", 1), "Flour can be sold");
        millEconomy.Tick(5);
        Check(millEconomy.Currency.Balance == 14 && millEconomy.EggsSold == 0, "Flour pays its price without advancing egg objective");
        Check(ProjectMeadow.Economy.TruckRoute.Offset(0) == 0 && ProjectMeadow.Economy.TruckRoute.Offset(1) == 0, "Truck starts and ends at parking");
        Check(!ProjectMeadow.Economy.TruckRoute.Visible(.5f) && ProjectMeadow.Economy.TruckRoute.Offset(.5f) == 22, "Truck waits offscreen during delivery");
        Check(ProjectMeadow.Economy.TruckRoute.Visible(.1f) && ProjectMeadow.Economy.TruckRoute.Visible(.9f) && ProjectMeadow.Economy.TruckRoute.Offset(.1f) > 0, "Truck has outbound and return legs");
        var upgradeStock = new ProjectMeadow.Inventory.InventoryService(4);
        var upgradeWallet = new ProjectMeadow.Economy.CurrencyService(); upgradeWallet.TryCredit(20);
        var upgradedMill = new ProjectMeadow.Production.ProductionService(upgradeStock, upgradeWallet, "grain", 2, "flour", 1, 6);
        upgradeStock.TryAdd("grain", 4); upgradedMill.TryQueue(); upgradedMill.TryQueue();
        upgradedMill.Tick(3); upgradedMill.TryUpgrade(); upgradedMill.Tick(2);
        Check(upgradeStock.Count("flour") == 0, "Upgrade preserves active job duration");
        upgradedMill.Tick(1); upgradedMill.Tick(4.8f);
        Check(upgradeStock.Count("flour") == 2, "Next queued job uses upgraded duration");
        var cowCycle = new ChickenCycle(3, 10);
        Check(!cowCycle.Tick(100) && cowCycle.BeginMeal(), "Cow requires a meal before producing milk");
        Check(!cowCycle.Tick(3) && !cowCycle.Tick(9), "Cow respects eating and production durations");
        Check(cowCycle.Tick(1) && !cowCycle.Tick(100), "Cow produces exactly one milk per meal");
        var dairyStock = new ProjectMeadow.Inventory.InventoryService(10);
        var dairyEconomy = new ProjectMeadow.Economy.EconomyService(dairyStock);
        var dairy = new ProjectMeadow.Production.ProductionService(dairyStock, dairyEconomy.Currency, "milk", 2, "cheese", 1, 8);
        var parallelMill = new ProjectMeadow.Production.ProductionService(dairyStock, dairyEconomy.Currency, "grain", 2, "flour", 1, 6);
        Check(!dairy.TryQueue(), "Cheese cannot be made without milk");
        dairyStock.TryAdd("milk", 2); dairyStock.TryAdd("grain", 2);
        Check(dairy.TryQueue() && parallelMill.TryQueue() && dairyStock.Used == 0, "Buildings reserve their own ingredients");
        dairy.Tick(6); parallelMill.Tick(6);
        Check(dairyStock.Count("flour") == 1 && dairyStock.Count("cheese") == 0, "Different recipes finish independently");
        dairy.Tick(2);
        Check(dairyStock.Count("cheese") == 1, "Two milk become one cheese after eight seconds");
        Check(dairyEconomy.TryDispatch("cheese", 1), "Cheese accepted by market");
        dairyEconomy.Tick(5);
        Check(dairyEconomy.Currency.Balance == 24 && dairyEconomy.EggsSold == 0, "Cheese sale pays 24 without advancing egg goal");
        dairyStock.TryAdd("milk", 1); dairyEconomy.TryDispatch("milk", 1); dairyEconomy.Tick(5);
        Check(dairyEconomy.Currency.Balance == 32 && dairyEconomy.EggsSold == 0, "Milk sale pays eight without advancing egg goal");
        Check(dairy.TryUpgrade() && parallelMill.UpgradeLevel == 0, "Building upgrades are independent");
        var c = new ChickenCycle(2, 5);
        Check(!c.Tick(100), "No production without food");
        Check(c.BeginMeal() && !c.BeginMeal(), "No overlapping meals");
        Check(!c.Tick(2) && c.State == ChickenCycle.Phase.ProductionCooldown, "Eating transitions to cooldown");
        Check(!c.Tick(4) && c.Tick(1), "Egg only after complete cooldown");
        Check(!c.Tick(100), "Exactly one egg per meal");
        Check(c.BeginMeal() && c.Tick(7), "Next meal produces another egg");
        c.BeginMeal();
        Check(!c.Tick(-10) && c.Tick(20) && !c.Tick(20), "Negative time ignored; large frame produces once");
    }
}
